const fn at(stage: Stage, rule: Rule) -> Pattern {
    Pattern { stage, rule }
}

const fn row(
    kind: ManifestKind,
    ecosystem: Ecosystem,
    provider: &'static str,
    format: ManifestFormat,
    patterns: &'static [Pattern],
) -> ManifestRow {
    ManifestRow {
        kind,
        ecosystem,
        provider,
        format,
        patterns,
    }
}

