#[test]
fn reads_every_dependency_section_upstream_and_master_read() {
    let mut missed = Vec::new();
    for &(setting, section, path, text, name, req) in SECTIONS {
        let read = found(&format!("/work/{path}"), text);
        if !read
            .iter()
            .any(|(n, r, _)| (n.as_str(), r.as_str()) == (name, req))
        {
            let got: Vec<_> = read.iter().map(|(n, r, _)| format!("{n}@{r}")).collect();
            missed.push(format!(
                "{setting}: {section} in {path}, want {name}@{req}, read {got:?}"
            ));
        }
    }
    assert!(
        missed.is_empty(),
        "{} of {} missed:\n{}",
        missed.len(),
        SECTIONS.len(),
        missed.join("\n")
    );
}
